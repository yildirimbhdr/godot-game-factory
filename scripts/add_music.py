#!/usr/bin/env python3
"""Add an optional music track to a game: copy it, measure loudness, record license in ASSETS.md.

OGG sources are copied untouched (no quality loss; this ffmpeg build has no good Vorbis encoder).
Other formats become 16-bit WAV. Loudness is not baked into the file: the needed gain is written to
assets/audio/music_gains.gd, which AudioManager applies when the track plays.

  add_music.py <project> <name> <file-or-url> --author NAME --license CC0 [--source-url URL]
<name> is what the game plays: AudioManager.play_music("<name>"). Only CC0 or licenses allowing
commercial use should be added; attribution licenses must also be credited in the game.
"""
import argparse, json, re, shutil, subprocess, sys, tempfile, urllib.request
from pathlib import Path


TARGET_LUFS = -20.0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("project"); ap.add_argument("name"); ap.add_argument("source")
    ap.add_argument("--author", required=True); ap.add_argument("--license", required=True)
    ap.add_argument("--source-url", default="")
    a = ap.parse_args()
    project = Path(a.project).resolve()
    music_dir = project / "assets" / "audio" / "music"
    music_dir.mkdir(parents=True, exist_ok=True)

    src = a.source
    tmp = None
    if src.startswith(("http://", "https://")):
        tmp = tempfile.NamedTemporaryFile(suffix=Path(src).suffix or ".audio", delete=False)
        urllib.request.urlretrieve(src, tmp.name)
        src = tmp.name
    codec = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "a:0", "-show_entries", "stream=codec_name",
                            "-of", "csv=p=0", src], check=True, capture_output=True, text=True).stdout.strip()
    for old in music_dir.glob(f"{a.name}.*"):
        old.unlink()
    if codec == "vorbis" and Path(src).suffix.lower() == ".ogg":
        out = music_dir / f"{a.name}.ogg"
        shutil.copyfile(src, out)
    else:
        out = music_dir / f"{a.name}.wav"
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src, "-ar", "44100", "-c:a", "pcm_s16le", str(out)], check=True)
    seconds = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(out)],
                                   check=True, capture_output=True, text=True).stdout)
    # integrated loudness; the target leaves room for SFX on top
    report = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(out), "-af", "loudnorm=I=-20:TP=-2:LRA=11:print_format=json",
                             "-f", "null", "-"], capture_output=True, text=True).stderr
    measured = float(re.search(r'"input_i"\s*:\s*"(-?[\d.]+)"', report).group(1))
    gain_db = round(max(-12.0, min(9.0, TARGET_LUFS - measured)), 1)
    lock_path = project / "assets" / "audio" / "music.lock.json"
    lock = json.loads(lock_path.read_text()) if lock_path.exists() else {}
    lock[a.name] = {"author": a.author, "license": a.license, "source_url": a.source_url or a.source, "seconds": round(seconds, 1), "file": out.name, "lufs": measured, "gain_db": gain_db}
    lock_path.write_text(json.dumps(lock, indent=2, sort_keys=True) + "\n")
    entries = ",\n".join(f'\t"{n}": {e["gain_db"]}' for n, e in sorted(lock.items()))
    (project / "assets" / "audio" / "music_gains.gd").write_text(
        "# Generated by scripts/add_music.py. Per-track gain in dB applied by AudioManager.\nextends RefCounted\n\n"
        f"const GAINS := {{\n{entries}\n}}\n")

    begin, end = "<!-- music:begin -->", "<!-- music:end -->"
    rows = "\n".join(f"| assets/audio/music/{e['file']} | music | {e['source_url']} | {e['author']} | {e['license']} | | {e['seconds']}s, gain {e['gain_db']} dB |"
                     for n, e in sorted(lock.items()))
    block = f"{begin}\n{rows}\n{end}"
    path = project / "ASSETS.md"
    text = path.read_text() if path.exists() else "# Assets\n\n| File(s) | Type | Source URL | Author | License | Date added | Notes |\n|---|---|---|---|---|---|---|\n"
    text = (text.split(begin)[0] + block + text.split(end, 1)[1]) if begin in text else text.rstrip("\n") + "\n" + block + "\n"
    path.write_text(text)
    print(f"{out.relative_to(project)}  {seconds:.1f}s  {measured} LUFS -> gain {gain_db} dB  ({a.license}, {a.author})")


if __name__ == "__main__":
    sys.exit(main())
