#!/usr/bin/env python3
"""The answer sheet for the store forms that no API can fill (Apple age rating, privacy labels, Play content rating, data safety ...).

  store_declarations.py <game> [--violence none|cartoon|realistic] [--kids] [--first-run-tutorial]

Looks at what the game really contains (ads/analytics SDKs, purchases, network code, accounts) and writes <game>/store/declarations.md:
for every form the exact answer, the reason, and where to click. About 10 minutes of copy-and-click per game, no Claude needed.
It is a proposal for the owner, who gives these legal declarations; if the game changes (ads added, analytics added) run it again.
"""
import re, sys
from pathlib import Path


def detect(game: Path) -> dict:
    def has(p): return (game / p).exists()
    gd = "\n".join(p.read_text(errors="ignore") for p in game.rglob("*.gd") if ".godot" not in p.parts and "addons" not in p.parts) if game.exists() else ""
    ads_script = (game / "autoload" / "ads.gd")
    mock_ads = ads_script.is_file() and "mock" in ads_script.read_text(errors="ignore").lower() and not has("addons/admob")
    return {
        "ads": has("addons/admob") or (ads_script.is_file() and not mock_ads),
        "analytics": has("addons/godotx_firebase"),
        "iap": bool(re.search(r"\b(purchase|billing|IAP|in_app)\b", gd, re.I)) and has("addons"),
        "network": bool(re.search(r"HTTPRequest|WebSocket|ENet|MultiplayerPeer", gd)),
        "account": bool(re.search(r"\blogin\b|sign_in|signin", gd, re.I)),
    }


def main(game: Path, violence: str, kids: bool) -> None:
    f = detect(game)
    name = game.name
    ads, an, iap = f["ads"], f["analytics"], f["iap"]
    collects = ads or an
    out = []
    A = out.append
    A(f"# Store form answers for {name}\n")
    A("Generated by `store_declarations.py` from what the project contains. Detected: " +
      ", ".join(f"{k}={'yes' if v else 'no'}" for k, v in f.items()) + ". Re-run after adding ads, analytics or purchases.\n")
    A("Legal declarations are yours: read each answer before you give it. Texts, images and builds come from `fastlane_prepare.py`.\n")

    A("## Apple App Store Connect (once per app)")
    A("| Form (where) | Answer | Why |\n|---|---|---|")
    A(f"| App Privacy > Get Started (Data Collection) | {'Yes, we collect data. Then: ' + ('Device ID + Advertising Data + Usage Data (AdMob), ' if ads else '') + ('Product Interaction + Diagnostics (Firebase Analytics)' if an else '') if collects else 'No, we do not collect data. Publish.'} | {'ads/analytics SDKs send data off the device' if collects else 'no SDK sends anything off the device'} |")
    A(f"| App Privacy > Privacy Policy URL | the `privacy_url` from store/status.json, entered for EVERY localized language | Add for Review fails if one locale is missing |")
    A(f"| App Information > Content Rights | Yes, I have the necessary rights (any Kenney / OFL / generated assets count as third-party content) | answer No only if every asset is your own |")
    sev = {"none": "None in every row", "cartoon": "Cartoon or Fantasy Violence = Infrequent, all other rows None (gives 9+)", "realistic": "Realistic Violence = Infrequent or Frequent according to the game (gives 12+ to 17+)"}[violence]
    A(f"| App Information > Age Ratings (7 steps) | Features: all No{' except Advertising = Yes' if ads else ''}. Mature themes, medical, sexual: None. Violence: {sev}. Gambling/loot box: None/No | the questionnaire is by content, not by audience |")
    A(f"| Version page > App Review Information | your name, phone with country code (+90...), email; untick Sign-in required unless the game has accounts | the phone is required and blocks Save |")
    A(f"| Pricing and Availability | Free (US $0, all 175 countries), availability All Countries | change later only if you add paid features |")
    A(f"| App Privacy > each data type: tracking | {'No, unless the game shows the App Tracking Transparency prompt (then Yes for Device ID and Advertising Data and add NSUserTrackingUsageDescription)' if ads else 'n/a'} | without the ATT prompt the IDFA is never delivered, so nothing is tracked |")
    A(f"| Submit | Export compliance: standard HTTPS only = exempt; Advertising Identifier: {'Yes (AdMob) and serve ads' if ads else 'No'} | |")
    A("")
    A("## Google Play Console (once per app)")
    A("| Form (App content > ...) | Answer | Why |\n|---|---|---|")
    A("| Create app | Game, Free, tick both declarations yourself | legal declarations |")
    A("| Privacy policy | the same URL | |")
    A("| App access | All functionality available without restrictions (Hayır/No) | no accounts |")
    A(f"| Ads | {'Yes, contains ads' if ads else 'No, no ads'} | |")
    A("| Content rating (IARC) | Category Game, your email, accept IARC terms. " + ("Violence: Yes > violence against non-humans/fantasy creatures, fantasy setting, pixelated, unrealistic reactions, rarely from afar, no blood. " if violence == "cartoon" else "Violence: No. ") + "Fear, sex, gambling, language, drugs, crude humor, purchases, location sharing, user interaction: No | answer the same way as Apple |")
    A(f"| Target audience | {'5 and under ... 12 (Families policy applies, ads limited)' if kids else '13-15, 16-17, 18+ (not for children)'} | 13+ avoids the Families Policy |")
    A(f"| Data safety | {'Collected/shared: Device or other IDs, App interactions, Diagnostics (from AdMob/Firebase); encrypted in transit yes; no account creation' if collects else 'Does your app collect or share any required user data types? No. Preview shows Data not collected, no sharing'} | must match Apple |")
    A(f"| Advertising ID | {'Yes, used for advertising' if ads else 'No'} | |")
    A("| Government apps / Financial features / Health | No / none of the features (tick the box at the bottom of the list) / none | |")
    A("| Store settings | Category (Puzzle for a puzzle game), public email, website = support page | |")
    A("| Store listing | per language: text from fastlane, icon, feature graphic, screenshots; then Yapay zekayla üretilmiş öğeler: tick every graphic that contains generated art | an unticked generated asset is a policy risk |")
    A("| Production > Countries | select all, Save | |")
    A("")
    A("## What changes when you add things later")
    A("- **AdMob:** Apple privacy labels (Device ID, Advertising Data, Usage Data), Advertising = Yes in age rating, Play Ads = Yes, Advertising ID = Yes, Data safety rows, UMP consent form, `app-ads.txt`.")
    A("- **Firebase Analytics:** Apple (Product Interaction, Diagnostics), Play Data safety (App interactions, Diagnostics), privacy policy paragraph (`privacy_policy.py` picks it up).")
    A("- **In-app purchases:** Apple IAP products + review screenshot, Play Digital purchases = Yes in IARC, price list.")
    A("- **Online features / accounts:** App access with test login, account deletion URL (Play), Sign in required in Apple review info.")
    p = game / "store" / "declarations.md"
    p.parent.mkdir(exist_ok=True)
    p.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote", p)


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args:
        sys.exit(__doc__)
    v = "none"
    if "--violence" in sys.argv:
        v = sys.argv[sys.argv.index("--violence") + 1]
        args = [a for a in args if a != v]
    main(Path(args[0]).resolve(), v, "--kids" in sys.argv)
